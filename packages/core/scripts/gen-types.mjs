// Generates src/generated/contract.ts from the pipeline's JSON Schema bundle.
// Run `npm run gen:types -w @threex/core` after `uv run threex-compile schema`.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const schemaFile = fileURLToPath(new URL("../../../schema/v1/threex.schema.json", import.meta.url));
const outFile = fileURLToPath(new URL("../src/generated/contract.ts", import.meta.url));

const bundle = JSON.parse(readFileSync(schemaFile, "utf8"));
const defs = bundle.$defs;
const refName = (ref) => ref.replace("#/$defs/", "");

// Pydantic titles every property ("Depthm"), which would become stray type aliases.
// Keep titles only on $defs entries, where they name the generated types.
function tidy(node, isDef = false) {
  if (Array.isArray(node)) return node.map((item) => tidy(item));
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "title" && !isDef) continue;
    out[key] = key === "$defs"
      ? Object.fromEntries(Object.entries(value).map(([name, def]) => [name, tidy(def, true)]))
      : tidy(value);
  }
  // Maps keyed by an enum (e.g. signals keyed by SignalId) become typed records.
  const keyRef = out.propertyNames?.$ref;
  if (keyRef && defs[refName(keyRef)]?.enum && typeof out.additionalProperties === "object") {
    const value = out.additionalProperties.$ref ? refName(out.additionalProperties.$ref) : "number";
    out.tsType = `Partial<Record<${refName(keyRef)}, ${value}>>`;
  }
  return out;
}

const { $id: _id, ...rest } = bundle; // json-schema-to-typescript would name the root after $id
const root = tidy({
  ...rest,
  title: "ThreeXContract",
  description: "The three documents the pipeline publishes.",
  type: "object",
  properties: {
    manifest: { $ref: "#/$defs/Manifest" },
    tile: { $ref: "#/$defs/Tile" },
    scoringConfig: { $ref: "#/$defs/ScoringConfig" },
  },
  required: ["manifest", "tile", "scoringConfig"],
  additionalProperties: false,
}, false);

const ts = await compile(root, "ThreeXContract", {
  additionalProperties: false,
  unreachableDefinitions: true,
  ignoreMinAndMaxItems: true,
  bannerComment:
    "/* Generated by packages/core/scripts/gen-types.mjs from schema/v1/threex.schema.json.\n" +
    " * Do not edit. Change pipeline/src/compiler/models.py, then regenerate. */",
});
// Drop the generator's "This interface was referenced by…" boilerplate from doc comments.
const boilerplate = / \* This interface was referenced by `ThreeXContract`'s JSON-Schema\n \* via the `definition` "\w+"\.\n/g;
const cleaned = ts
  .replace(boilerplate, "")
  .replace(/\/\*\*\n \*\/\n/g, "")
  .replace(/\n \*\n \*\//g, "\n */");
writeFileSync(outFile, cleaned);
console.log(`Wrote ${outFile}`);
